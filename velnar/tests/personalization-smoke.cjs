// End-to-end checks use a disposable extension profile and no signed-in account.
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const root = path.resolve(__dirname, "..");

(async () => {
  const artifacts = path.join(root, "artifacts/personalization");
  fs.mkdirSync(artifacts, { recursive: true });
  const context = await chromium.launchPersistentContext(fs.mkdtempSync(path.join(os.tmpdir(), "nexora-personalization-")), {
    executablePath: process.env.NEXORA_BROWSER || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    headless: true, viewport: { width: 1440, height: 1040 },
    args: [`--disable-extensions-except=${path.join(root, "extension")}`, `--load-extension=${path.join(root, "extension")}`]
  });
  const errors = [];
  context.on("page", page => page.on("pageerror", error => errors.push(error.message)));
  try {
    const worker = context.serviceWorkers()[0] || await context.waitForEvent("serviceworker");
    const base = `chrome-extension://${worker.url().split("/")[2]}`;
    const page = await context.newPage();
    await page.goto(`${base}/options/options.html`);
    await page.locator(".gs-theme-choice").first().waitFor();
    const read = () => page.evaluate(() => NEXORA.Storage.get());
    await page.locator('[data-tab="builder"]').click();
    assert.equal(await page.locator("#btnUseBuilderPreset").isDisabled(), true);
    await page.locator("#builderPreset").selectOption("paper-and-ink");
    await page.locator("#btnUseBuilderPreset").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).builderDraft?.colors.background === "#fcf8ee");
    assert.equal(await page.locator("#themeNameInput").inputValue(), "Paper & Ink");
    assert.equal((await read()).activeThemeId, "dark");
    await page.locator("#themeNameInput").fill("پالت شخصی");
    await page.locator("#paletteSeed").evaluate(element => { element.value = "#7c9dff"; });
    await page.locator("#paletteMode").selectOption("light");
    await page.locator("#btnGeneratePalette").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).builderDraft?.colors.accent === "#7c9dff");
    assert.equal((await read()).activeThemeId, "dark");
    assert.equal((await read()).appearanceHistory.length, 0);
    assert.equal(await page.locator("#readabilityChecks .is-low").count(), 0);
    await page.locator("#btnSavePersonal").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).personalThemes.length === 1);
    const personalId = (await read()).personalThemes[0].id;
    await page.locator('[data-tab="themes"]').click();
    await page.locator('[data-category="personal"]').click();
    assert.equal(await page.locator(".gs-theme-choice").count(), 1);
    const exportPending = page.waitForEvent("download");
    await page.locator(`[data-theme-id="${personalId}"]`).getByRole("button", { name: "Export پالت شخصی as JSON" }).click();
    const exportFile = await (await exportPending).path();
    const { name, colors } = (await read()).personalThemes[0];
    assert.deepEqual(JSON.parse(fs.readFileSync(exportFile, "utf8")), { name, colors });
    await page.locator(`[data-theme-id="${personalId}"] .studio-inspect`).click();
    await page.locator('[data-surface="review"]').click();
    assert.equal(await page.locator("#workspacePreview .sample-diff .added").count(), 2);
    const beforePreview = await read();
    await page.locator("#btnCompare").click();
    assert.deepEqual(await read(), beforePreview);
    assert.equal(await page.locator("#compareCurrent .sample-diff").count(), 1);
    await page.locator("#btnApplyCompared").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).customThemeApplied);
    await page.locator(`[data-theme-id="${personalId}"] .gs-fav-star`).click();
    await page.reload();
    await page.locator("#activeThemeName").filter({ hasText: "پالت شخصی" }).waitFor();
    assert.equal(await page.locator("#btnUndoTheme").isEnabled(), true, "undo persists after reload");
    await page.locator('[data-category="personal"]').click();
    await page.locator(`[data-theme-id="${personalId}"] .personal-actions button`).first().click();
    await page.locator("#themeNameInput").fill("Renamed palette");
    await page.locator("#btnSavePersonal").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).personalThemes[0].name === "Renamed palette");
    assert.equal((await read()).customTheme.name, "پالت شخصی", "editing preserves the applied copy");
    await page.locator("#btnSaveCopy").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).personalThemes.length === 2);
    await page.locator("#themeNameInput").fill("Unfinished draft");
    const background = (await read()).builderDraft.colors.background;
    const primary = page.getByRole("textbox", { name: "Text Primary color value", exact: true });
    await primary.fill(background); await primary.press("Tab");
    await page.locator('#readabilityChecks [aria-label="Fix Primary text"]').click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).builderDraft?.colors.textPrimary !== (await NEXORA.Storage.get()).builderDraft?.colors.background);
    const draft = (await read()).builderDraft;
    await page.reload();
    await page.locator('[data-tab="builder"]').click();
    assert.equal(await page.locator("#themeNameInput").inputValue(), "Unfinished draft");
    assert.equal(await page.getByRole("textbox", { name: "Text Primary color value", exact: true }).inputValue(), draft.colors.textPrimary);
    assert.match(await page.locator("#draftStatus").textContent(), /recovered/);
    await page.screenshot({ path: path.join(artifacts, "builder.png"), fullPage: true });
    await page.locator('[data-tab="themes"]').click();
    await page.locator('[data-category="personal"]').click();
    await page.locator(`[data-theme-id="${personalId}"] .personal-actions button`).last().click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).personalThemes.length === 1);
    assert.equal((await read()).customTheme.name, "پالت شخصی");
    assert.equal((await read()).favoriteThemeIds.includes(personalId), false);
    const popup = await context.newPage(); await popup.setViewportSize({ width: 380, height: 600 });
    await popup.goto(`${base}/popup/popup.html`);
    await popup.locator(".gs-theme-select").first().waitFor();
    await page.locator('[data-tab="settings"]').click();
    await page.locator("#interfaceLanguage").selectOption("fa");
    await page.waitForFunction(() => document.documentElement.lang === "fa");
    await popup.waitForFunction(() => document.documentElement.dir === "rtl");
    await page.locator('[data-tab="builder"]').click();
    await page.getByRole("button", { name: "تولید رنگ‌های هماهنگ", exact: true }).waitFor();
    assert.equal(await page.locator("#themeNameInput").inputValue(), "Unfinished draft");
    await page.locator('[data-tab="typography"]').click();
    assert.equal(await page.locator("#typographyPreview code").evaluate(el => getComputedStyle(el).direction), "ltr");
    await page.locator('[data-tab="themes"]').click();
    await page.locator('[data-category="personal"]').click();
    await page.locator(".studio-inspect").click();
    await page.locator('[data-surface="review"]').click();
    assert.equal(await page.locator("#workspacePreview .sample-diff").evaluate(el => getComputedStyle(el).direction), "ltr");
    await page.locator("#btnCompare").click();
    await page.screenshot({ path: path.join(artifacts, "review-fa.png"), fullPage: true });
    await page.locator("#btnCloseCompare").click();
    await popup.locator('[data-category="personal"]').click();
    assert.equal(await popup.locator(".gs-theme-select").count(), 1);
    assert.equal(await popup.locator("#btnSettings").textContent(), "باز کردن تنظیمات");
    assert.equal(await popup.locator(".gs-swatch-name").textContent(), "Renamed palette");
    assert.equal(await popup.evaluate(() => document.documentElement.scrollHeight <= innerHeight), true);
    await popup.evaluate(() => NEXORA.UI.status(""));
    await popup.screenshot({ path: path.join(artifacts, "popup-fa.png"), fullPage: true });
    for (const width of [390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1040 });
      for (const tab of ["themes", "builder", "settings"]) {
        await page.locator(`[data-tab="${tab}"]`).click();
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${tab} RTL overflow at ${width}`);
      }
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('[data-tab="builder"]').click();
    await page.screenshot({ path: path.join(artifacts, "builder-fa-mobile.png"), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1040 });
    await page.locator('[data-tab="importexport"]').click();
    const downloadPending = page.waitForEvent("download");
    await page.locator("#btnBackupSettings").click();
    const backupFile = await (await downloadPending).path();
    const backup = JSON.parse(fs.readFileSync(backupFile, "utf8"));
    assert.equal(backup.language, "fa"); assert.equal(backup.personalThemes.length, 1);
    await page.evaluate(() => NEXORA.Storage.reset());
    await page.waitForFunction(() => document.documentElement.lang === "en");
    await page.locator("#restoreSettingsFile").setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(backup)) });
    await page.waitForFunction(() => document.documentElement.lang === "fa");
    assert.deepEqual(await read(), backup, "complete backup includes draft, library, history and language");
    await page.locator('[data-tab="settings"]').click();
    await page.locator("#interfaceLanguage").selectOption("en");
    await popup.waitForFunction(() => document.documentElement.lang === "en");
    assert.equal(await popup.locator("#btnSettings").textContent(), "Open Settings");
    await page.locator('[data-tab="typography"]').click();
    await page.locator("#btnReadingComfort").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).typography.fontSize === 16);
    await page.reload();
    await page.locator(".gs-theme-choice").first().waitFor();
    await page.locator("#btnUndoTheme").click();
    await page.waitForFunction(async () => (await NEXORA.Storage.get()).typography.fontSize === 14);
    assert.equal((await read()).personalThemes.length, 1); assert.equal((await read()).language, "en");
    await page.locator('[data-tab="settings"]').click();
    const historyLength = (await read()).appearanceHistory.length;
    await page.locator("#appearanceHistory button").first().click();
    await page.waitForFunction(async length => (await NEXORA.Storage.get()).appearanceHistory.length < length, historyLength);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(artifacts, "results.json"), JSON.stringify({ passed: true, browser: context.browser().version(), checks: ["personal themes", "generation", "readability repair", "review comparison", "persistent history", "draft recovery", "backup roundtrip", "live localization", "RTL responsive layout"], errors }, null, 2));
    console.log("PASS: personal theme lifecycle, generated palette, readability repair, review comparison, draft recovery, history, backup, live EN/FA and responsive RTL");
  } finally { await context.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
